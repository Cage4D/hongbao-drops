// Build step: embed the fonts the media renderer needs as base64 modules under src/generated/
// (gitignored), so serverless bundlers include them via ordinary imports — Vercel's zero-config
// NestJS build doesn't support `includeFiles`. Run by `pnpm build` before tsc.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkgDir = (name) => dirname(require.resolve(`${name}/package.json`));
const outDir = fileURLToPath(new URL('../src/generated/fonts/', import.meta.url));
mkdirSync(outDir, { recursive: true });

const fonts = {
  'inter.ts': {
    INTER_BOLD: join(pkgDir('@expo-google-fonts/inter'), '700Bold', 'Inter_700Bold.ttf'),
    INTER_EXTRABOLD: join(pkgDir('@expo-google-fonts/inter'), '800ExtraBold', 'Inter_800ExtraBold.ttf'),
  },
  // Separate module: ~14 MB of base64, only imported when a message contains CJK.
  'noto-sans-sc.ts': {
    NOTO_SC_BOLD: join(pkgDir('@expo-google-fonts/noto-sans-sc'), '700Bold', 'NotoSansSC_700Bold.ttf'),
  },
};

for (const [file, entries] of Object.entries(fonts)) {
  const body = Object.entries(entries)
    .map(([name, path]) => `export const ${name} = '${readFileSync(path).toString('base64')}';`)
    .join('\n');
  writeFileSync(join(outDir, file), `/* generated by tools/embed-fonts.mjs — do not edit */\n${body}\n`);
  console.log(`embedded ${Object.keys(entries).join(', ')} → src/generated/fonts/${file}`);
}
